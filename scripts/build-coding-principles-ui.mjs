import { build } from 'esbuild';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/coding-principles-ui.mjs'],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  minify: true,
  legalComments: 'inline',
  metafile: true,
  write: false,
});
const packages = new Set(Object.keys(result.metafile.inputs).flatMap(path => {
  const name = path.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1];
  return name ? [name] : [];
}));
const licenses = [];
for (const name of [...packages].sort()) {
  const directory = join(root, 'node_modules', name);
  const filename = (await readdir(directory)).find(file => /^licen[cs]e(?:\.|$)/i.test(file));
  if (!filename) throw new Error(`Missing bundled license: ${name}`);
  licenses.push(`${name}\n${await readFile(join(directory, filename), 'utf8')}`);
}
const banner = `/* Generated by npm run build:coding-principles-ui.\nBundled dependency licenses:\n\n${licenses.join('\n\n')}\n*/\n`;
await writeFile(join(root, 'scripts/coding-principles-ui.cjs'), banner + result.outputFiles[0].text);
